"""Cut the character sheet (assets/img/planche.png) into a clean plate + transparent sprites.

The plate is the sheet with every animated element painted out with the local paper colour.
Each sprite is that element with the paper turned transparent (colour-to-alpha), so it can
pop, shake or spin over the plate. Everything is upscaled x3 (Lanczos) for the close-ups.
Writes assets/img/plate.png, assets/img/sprites/<name>.png and assets/sprites.js.
"""
import json
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets/img/planche.png")
UP = 3

SPRITES = {
    # panel 1
    "p1_bubble": (439, 200, 604, 294),
    "p1_ticks_head": (335, 41, 394, 107),
    "p1_ticks_lap": (415, 111, 459, 150),
    # panel 2
    "p2_text": (1080, 26, 1372, 139),
    "p2_tick": (1060, 126, 1110, 173),
    "p2_spiral": (960, 14, 1014, 74),
    "p2_bubble": (1134, 197, 1323, 303),
    # panel 3
    "p3_tap1": (379, 476, 432, 509),
    "p3_tap2": (384, 510, 432, 546),
    "p3_tap3": (377, 549, 438, 584),
    "p3_spiral": (333, 376, 394, 456),
    "p3_bubble": (458, 520, 621, 656),
    # panel 4
    "p4_puffL": (700, 394, 781, 465),
    "p4_puffR": (1125, 381, 1203, 447),
    "p4_mL": (690, 474, 756, 525),
    "p4_mT": (1057, 376, 1121, 430),
    "p4_mR": (1127, 449, 1181, 535),
    "p4_bubble": (1192, 514, 1379, 653),
    # panel 5
    "p5_ah": (559, 785, 655, 881),
    "p5_dots": (855, 793, 946, 830),
    "p5_cloud": (926, 730, 1352, 986),
    "p5_ticks_head": (226, 738, 303, 794),
    "p5_bubble": (690, 904, 876, 1002),
}


def main():
    im = Image.open(SRC).convert("RGB")
    a = np.asarray(im).astype(np.float32)
    plate = a.copy()
    os.makedirs(os.path.join(ROOT, "assets/img/sprites"), exist_ok=True)
    meta = {}
    for name, (x0, y0, x1, y1) in SPRITES.items():
        crop = a[y0:y1, x0:x1]
        # local paper colour: median of the light pixels on the rect border
        border = np.concatenate([crop[0], crop[-1], crop[:, 0], crop[:, -1]])
        light = border[border.mean(1) > 225]
        bg = np.median(light if len(light) else border, axis=0)
        # colour-to-alpha against bg
        alpha = np.clip(((bg - crop) / np.maximum(bg, 1)).max(axis=2) * 1.15, 0, 1)
        alpha[alpha < 0.06] = 0
        col = np.where(alpha[..., None] > 0, (crop - (1 - alpha[..., None]) * bg) / np.maximum(alpha[..., None], 1e-3), 0)
        rgba = np.dstack([np.clip(col, 0, 255), alpha * 255]).astype(np.uint8)
        spr = Image.fromarray(rgba, "RGBA").resize(((x1 - x0) * UP, (y1 - y0) * UP), Image.LANCZOS)
        spr.save(os.path.join(ROOT, f"assets/img/sprites/{name}.png"), optimize=True)
        # paint the element out of the plate
        plate[y0:y1, x0:x1] = bg
        meta[name] = [x0, y0, x1 - x0, y1 - y0]
    Image.fromarray(plate.astype(np.uint8)).resize((im.width * UP, im.height * UP), Image.LANCZOS).save(
        os.path.join(ROOT, "assets/img/plate.png"), optimize=True)
    paper = np.median(a[a.mean(2) > 240], axis=0)
    with open(os.path.join(ROOT, "assets/sprites.js"), "w") as f:
        f.write("/* Generated by tools/cut_sheet.py: sprite rects [x, y, w, h] in sheet pixels. */\n")
        f.write("window.Doodle = window.Doodle || {};\n")
        f.write(f"window.Doodle.SPRITES = {json.dumps(meta)};\n")
        f.write(f"window.Doodle.PAPER = 'rgb({int(paper[0])},{int(paper[1])},{int(paper[2])})';\n")


if __name__ == "__main__":
    main()
