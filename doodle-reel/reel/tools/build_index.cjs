// Writes index.html: the 8 scene hosts and every sound clip, timed from the same
// cue list the drawings read (assets/rig.js -> Rig.CUES). Run: node tools/build_index.cjs
const fs = require("fs");
const path = require("path");
global.window = {};
global.document = {};
require(path.join(__dirname, "../assets/rig.js"));
const C = window.Rig.CUES;

// Peaks of the files (measured with ffmpeg volumedetect), so data-volume = target / peak.
const PEAK = { "key-soft": 0.537, "key-press": 0.519, thud: 0.955, pop: 0.692, click: 0.537 };
function rng(seed) {
  const r = window.Rig.rng(seed);
  return (a, b) => a + (b - a) * r();
}
const vary = rng(7);
const audio = [];
let n = 0;
function clip(file, t, target, dur) {
  n++;
  const v = (target / PEAK[file]).toFixed(3);
  audio.push(
    `      <audio id="sfx-${String(n).padStart(2, "0")}" class="clip" src="assets/audio/${file}.mp3" data-start="${t.toFixed(2)}" data-duration="${dur}" data-track-index="${3 + (n % 6)}" data-volume="${v}"></audio>`,
  );
}
C.L1.forEach((t) => clip("key-soft", t, 0.1 * vary(0.8, 1.15), 0.36));
clip("key-press", C.ENTER[1], 0.12, 0.4);
C.L2.forEach((t) => clip("key-press", t, 0.2 * vary(0.85, 1.12), 0.4));
clip("key-press", C.ENTER[2], 0.26, 0.4);
C.L3.forEach((t) => clip("key-press", t, 0.32 * vary(0.95, 1.05), 0.4));
clip("key-press", C.ENTER[3], 0.36, 0.4);
clip("thud", C.THUD, 0.45, 2.1);
clip("pop", C.POP, 0.14, 0.7);
C.TICKS.forEach((t) => clip("click", t, 0.07, 0.36));

const S = C.SCENE_START;
const hosts = S.slice(0, 8)
  .map((s, i) => {
    const id = `s${i + 1}`;
    return `      <div id="${id}" data-composition-id="${id}" data-composition-src="compositions/scene${i + 1}.html" data-start="${s}" data-duration="${S[i + 1] - s}" data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920"></div>`;
  })
  .join("\n");

const html = `<!doctype html>
<html lang="fr">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/rig.js"></script>
    <style>
      :root {
        --paper: #f6efe3;
      }
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        width: 1080px;
        height: 1920px;
        overflow: hidden;
        background: var(--paper);
      }
      #paper {
        position: absolute;
        inset: 0;
        background: var(--paper);
      }
    </style>
  </head>
  <body>
    <!-- generated by tools/build_index.cjs from the cue list in assets/rig.js -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="30" data-width="1080" data-height="1920">
      <div id="paper"></div>
${hosts}
      <audio id="music" class="clip" src="assets/audio/music.wav" data-start="0" data-duration="30" data-track-index="2" data-volume="1"></audio>
${audio.join("\n")}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
fs.writeFileSync(path.join(__dirname, "../index.html"), html);
console.log("index.html:", n, "sound clips");
